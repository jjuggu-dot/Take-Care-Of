private func tone(_ ch: Character) -> Color? {
    switch ch {
    case "0": return Color(red: 0.86, green: 0.90, blue: 0.78)
    case "4": return Color(red: 0.64, green: 0.71, blue: 0.56)
    case "1": return Color(red: 0.49, green: 0.54, blue: 0.43)
    case "2": return Color(red: 0.31, green: 0.35, blue: 0.27)
    case "3": return Color(red: 0.14, green: 0.18, blue: 0.12)
    default: return nil
    }
}

struct ContentView: View {
    @State private var breathing = false
    @State private var showHeart = false

    var body: some View {
        ZStack {
            Color(red: 0.71, green: 0.77, blue: 0.63).ignoresSafeArea()
            Canvas { context, size in
                let rows = Crow.front
                let columns = rows.first?.count ?? 1
                let scale = min(size.width / CGFloat(columns), size.height / CGFloat(rows.count))
                let originX = (size.width - scale * CGFloat(columns)) / 2
                let originY = (size.height - scale * CGFloat(rows.count)) / 2
                for (y, row) in rows.enumerated() {
                    for (x, ch) in row.enumerated() {
                        guard let color = tone(ch) else { continue }
                        let rect = CGRect(x: originX + CGFloat(x) * scale,
                                          y: originY + CGFloat(y) * scale,
                                          width: scale, height: scale)
                        context.fill(Path(rect), with: .color(color), style: FillStyle(antialiased: false))
                    }
                }
            }
            .padding(12)
            .offset(y: breathing ? -2 : 0)

            if showHeart {
                Image(systemName: "heart.fill")
                    .font(.title3)
                    .foregroundColor(Color(red: 0.14, green: 0.18, blue: 0.12))
                    .offset(x: 45, y: -55)
            }
        }
        .contentShape(Rectangle())
        .onTapGesture {
            showHeart = true
            DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { showHeart = false }
        }
        .onAppear {
            withAnimation(.easeInOut(duration: 1.0).repeatForever(autoreverses: true)) {
                breathing = true
            }
        }
    }
}
